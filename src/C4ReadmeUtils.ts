import { EC4DiagramType, ETimeWindow, IDocGenOptions } from './DocGenTypes';

/** Number of milliseconds per day, used for README staleness checks. */
export const MS_PER_DAY = 86400000;

/** Time-window durations in days. */
export const TIME_WINDOW_DAYS: Record<ETimeWindow, number> = {
   [ETimeWindow.kOneWeek]:  7,
   [ETimeWindow.kTwoWeeks]: 14,
   [ETimeWindow.kOneMonth]: 30
};

/** Maps EC4DiagramType to its generated output filename. */
export const C4_OUTPUT_FILES: Record<EC4DiagramType, string> = {
   [EC4DiagramType.kComponent]: 'README.StrongAI.Component.md',
   [EC4DiagramType.kContext]:   'README.StrongAI.Context.md',
};

/** Regex matching the datestamp embedded at the top of generated README files. */
export const README_DATESTAMP_RE = /^<!-- Generated by StrongAIAutoDoc (\d{8}) -->/m;

/** Prefix for the generated README datestamp comment. */
export const README_DATESTAMP_PREFIX = '<!-- Generated by StrongAIAutoDoc ';

/** Suffix for the generated README datestamp comment. */
export const README_DATESTAMP_SUFFIX = ' -->';

/**
 * Formats a Date as a compact YYYYMMDD string.
 * @param date - Date to format
 * @returns YYYYMMDD string
 */
export function formatDateYYYYMMDD(date: Date): string {
   const y = date.getFullYear();
   const m = String(date.getMonth() + 1).padStart(2, '0');
   const d = String(date.getDate()).padStart(2, '0');
   return `${y}${m}${d}`;
}

/**
 * Parses a YYYYMMDD string into a Date, returning null if malformed.
 * @param s - Date string to parse
 * @returns Parsed date or null
 */
export function parseDateYYYYMMDD(s: string): Date | null {
   if (!/^\d{8}$/.test(s)) return null;
   const year  = parseInt(s.substring(0, 4), 10);
   const month = parseInt(s.substring(4, 6), 10) - 1;
   const day   = parseInt(s.substring(6, 8), 10);
   const d = new Date(year, month, day);
   if (d.getFullYear() !== year || d.getMonth() !== month || d.getDate() !== day) {
      return null;
   }
   return d;
}

/**
 * Returns true if generated README content is absent or older than the configured time window.
 * @param existingContent - Current file content, if any
 * @param options - Doc-gen options including jobStartedAt and timeWindow
 * @returns True when regeneration is required
 */
export function isReadmeOutputStale(existingContent: string | null, options: IDocGenOptions): boolean {
   if (!existingContent) return true;
   const match = README_DATESTAMP_RE.exec(existingContent);
   if (!match) return true;
   const headerDate = parseDateYYYYMMDD(match[1]);
   if (!headerDate) return true;
   const ageMs       = options.jobStartedAt.getTime() - headerDate.getTime();
   const thresholdMs = TIME_WINDOW_DAYS[options.timeWindow] * MS_PER_DAY;
   return ageMs > thresholdMs;
}

/**
 * Builds the datestamp prefix written to the top of generated README files.
 * @param jobStartedAt - Job start timestamp
 * @returns Datestamp line with trailing blank line
 */
export function buildReadmeDatestamp(jobStartedAt: Date): string {
   const dateStr = formatDateYYYYMMDD(jobStartedAt);
   return `${README_DATESTAMP_PREFIX}${dateStr}${README_DATESTAMP_SUFFIX}\n\n`;
}
